"""Embed the HLSL sources as C++ raw string literals (compiled at runtime with D3DCompile)."""
import sys, pathlib
out, main, ffx_a, ffx_fsr1 = map(pathlib.Path, sys.argv[1:5])
DELIM = "VUSRC"
def lit(name, path):
    text = path.read_text(encoding="utf-8")
    assert f'){DELIM}"' not in text
    return f'static const char {name}[] = R"{DELIM}({text}){DELIM}";\n'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// generated by tools/embed_shaders.py - do not edit\n#pragma once\n"
               + lit("kShaderMain", main) + lit("kFfxA", ffx_a) + lit("kFfxFsr1", ffx_fsr1), encoding="utf-8")
